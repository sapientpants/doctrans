defmodule DoctransWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :doctrans

  # The session is stored in a cookie that is both signed and encrypted,
  # so its contents cannot be read or tampered with.
  @session_options [
    store: :cookie,
    key: "_doctrans_key",
    signing_salt: "Qr5ZNHs0",
    encryption_salt: "Zm5XkR8p",
    same_site: "Lax",
    # Not `Secure`: the app is served over plain HTTP on loopback or a LAN
    # address, and a `Secure` cookie would simply not be stored, breaking the
    # session. Confidentiality comes from the deployment binding, not the flag.
    secure: false,
    http_only: true
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # The first plug, ahead of static serving, so a request for a host this
  # deployment does not answer to is refused before `/uploads` or anything else
  # is served. The socket above is dispatched before any plug, so `/live` relies
  # on `check_origin` instead; see the plug's moduledoc.
  plug DoctransWeb.Plugs.AllowedHost

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :doctrans,
    gzip: not code_reloading?,
    only: DoctransWeb.static_paths()

  # Serve generated page images only; retained sources and converted PDFs
  # share the upload root but must never be exposed by static serving.
  # These contain private document content: prevent browser/proxy storage,
  # including requests with Plug.Static's versioned query strings.
  # `Plug.Static` resolves the MFA per request, so serving reads the same setting
  # the writers use (`Doctrans.Config.Uploads`).
  plug DoctransWeb.Plugs.UploadImages,
    at: "/uploads",
    from: {Doctrans.Config.Uploads, :upload_dir, []},
    gzip: false,
    cache_control_for_etags: "private, no-store",
    cache_control_for_vsn_requests: "private, no-store"

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :doctrans
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # The default body limit is enough: document uploads travel over the LiveView
  # socket, which bypasses this plug, and the router has no POST route, so no
  # multipart body sized to `:max_file_size` ever reaches it.
  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug DoctransWeb.Router
end

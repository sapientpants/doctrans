# DATABASE_HOST env var allows overriding for Docker (e.g., "db" for docker-compose)
config :doctrans, Doctrans.Repo,
  username: "postgres",
  password: "postgres",
  hostname: System.get_env("DATABASE_HOST", "localhost"),
  database: "doctrans_dev",
  stacktrace: true,
  show_sensitive_data_on_connection_error: true,
  pool_size: 10

# The listener (`http: [ip: ..., port: ...]`) is deliberately not configured
# here. `config/runtime.exs` runs in development too, and it is where the
# PHX_BIND_IP and PORT variables are read for every environment that starts a
# server, so the loopback default and the address parsing are stated once. It
# also runs after the `.env` loader, which this file is too early for.
#
# The binding deliberately does not follow DATABASE_HOST. Pointing development
# at a database on another host says nothing about who should be able to reach
# the *app*, and deriving one from the other meant that changing where Postgres
# lives silently published an unauthenticated app on every interface.

# For development, we disable any cache and enable code reloading.
#
# `debug_errors` stays off (#333). When it is on, `Phoenix.Endpoint` compiles
# `Plug.Debugger` into the endpoint, and the debugger answers
# `POST /__plug__/debugger/action` ahead of every plug: it verifies a signed
# term against `secret_key_base` and applies the MFA inside. No host check, no
# session and no CSRF token stand in front of it, so the signature is the only
# gate, and a page in the browser can deliver the POST as a plain form. An error
# renders Phoenix's ordinary error page instead; the stacktrace is in the
# terminal.
#
# `secret_key_base` and the LiveView signing salt are not set here either:
# `config/runtime.exs` resolves them per machine (see `Doctrans.Config.DevSecret`).
#
# `check_origin` is deliberately not set here. It used to be `false`, which
# admits any Origin on the LiveView socket; `config/runtime.exs` now configures
# the one explicit allowlist for every environment that serves, development
# included, so a DNS-rebinding page cannot drive the socket (#259).
#
# The watchers configuration can be used to run external
# watchers to your application. For example, we can use it
# to bundle .js and .css sources.
config :doctrans, DoctransWeb.Endpoint,
  code_reloader: true,
  debug_errors: false,
  watchers: [
    esbuild: {Esbuild, :install_and_run, [:doctrans, ~w(--sourcemap=inline --watch)]},
    tailwind: {Tailwind, :install_and_run, [:doctrans, ~w(--watch)]}
  ]

# ## SSL Support
#
# In order to use HTTPS in development, a self-signed
# certificate can be generated by running the following
# Mix task:
#
#     mix phx.gen.cert
#
# Run `mix help phx.gen.cert` for more information.
#
# The `http:` listener from `config/runtime.exs` can be replaced with:
#
#     https: [
#       port: 4001,
#       cipher_suite: :strong,
#       keyfile: "priv/cert/selfsigned_key.pem",
#       certfile: "priv/cert/selfsigned.pem"
#     ],
#
# If desired, both `http:` and `https:` keys can be
# configured to run both http and https servers on
# different ports.

# Watch static and templates for browser reloading.
#
# `web_console_logger` stays off, and this is the one place the reason is
# written out (#265). When the flag is on, joining the live-reload channel
# subscribes the joiner to every log event the server emits, and development
# logs at `:debug`: every LiveView event with its parameters (the chat message
# typed, the search query), every SQL statement with its bound page and chunk
# text, and the raw body of a failed inference request. The channel's socket
# accepts any join, so the only things between a page in the browser and that
# stream were the origin allowlist in `config/runtime.exs` and this flag. The
# development terminal already shows the same log; the browser console does not
# need a second copy.
#
# What a joiner still receives is what the channel itself serves: asset-change
# pushes, the checkout's path (`File.cwd!/0`) and the `PLUG_EDITOR` value, both
# of which the click-to-editor shortcuts in `assets/js/app.js` need. The origin
# allowlist is what gates those, and neither says anything about a document.
config :doctrans, DoctransWeb.Endpoint,
  live_reload: [
    web_console_logger: false,
    patterns: [
      ~r"priv/static/(?!uploads/).*(js|css|png|jpeg|jpg|gif|svg)$",
      ~r"priv/gettext/.*(po)$",
      ~r"lib/doctrans_web/(?:controllers|live|components|router)/?.*\.(ex|heex)$"
    ]
  ]

